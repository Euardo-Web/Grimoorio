def png(portrait=False):
    w,h=(300,400) if portrait else (640,360)
    raw=bytearray()
    for y in range(h):
        raw.append(0)
        for x in range(w):
            if portrait:
                silhouette=(x-w*.5)**2/(w*.2)**2+(y-h*.36)**2/(h*.18)**2<1 or ((x-w*.5)**2/(w*.38)**2+(y-h*.9)**2/(h*.35)**2<1)
                color=(30,41,42) if silhouette else (int(100+80*y/h),int(115+40*y/h),int(110-30*y/h))
            else:
                ridge=h*.52+38*math.sin(x/95)+18*math.sin(x/43)
                color=(25,56,49) if y>ridge else (int(80+100*y/h),int(110+65*y/h),int(120+15*y/h))
                if (x-w*.77)**2+(y-h*.24)**2<(h*.09)**2:color=(231,201,142)
                if y>h*.78+20*math.sin(x/70):color=(18,35,33)
            raw.extend(color)
    def chunk(kind,data):return struct.pack(">I",len(data))+kind+data+struct.pack(">I",zlib.crc32(kind+data)&0xffffffff)
    return b"\x89PNG\r\n\x1a\n"+chunk(b"IHDR",struct.pack(">IIBBBBB",w,h,8,2,0,0,0))+chunk(b"IDAT",zlib.compress(bytes(raw)))+chunk(b"IEND",b"")
